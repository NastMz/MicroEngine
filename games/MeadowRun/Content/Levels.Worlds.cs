    /// <summary>
    /// Fills open castle interior (below the ceiling) with back wall, leaving tall arched windows that
    /// show the burning sky. Saves authoring hundreds of '%' characters and keeps windows rhythmic.
    /// </summary>
    private static string[] Castleize(string[] rows)
    {
        var result = new string[rows.Length];
        for (int y = 0; y < rows.Length; y++)
        {
            var chars = rows[y].ToCharArray();
            for (int x = 0; x < chars.Length; x++)
            {
                if (chars[x] != '.' || y < 2 || y > 11) continue;
                bool window = y is >= 3 and <= 6 && x % 14 is >= 5 and <= 7 && !(y == 3 && x % 14 != 6);
                if (!window) chars[x] = '%';
            }
            result[y] = new string(chars);
        }
        return result;
    }

