#!/usr/bin/env node
// Writes BidiClasses.g.cs, the Unicode bidirectional class of every code point as sorted ranges, from Unicode's
// DerivedBidiClass.txt (the Unicode Character Database, extracted/; Unicode License v3, THIRD-PARTY-NOTICES.md).
//   node src/MicroEngine.Text.Shaping/Bidi/generate.mjs <DerivedBidiClass.txt>
// The file's @missing lines give the defaults of unassigned code points (right to left in the Hebrew and Arabic
// blocks, for example); its other lines override them.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2] ?? (() => { throw new Error('usage: generate.mjs <DerivedBidiClass.txt>'); })();
const text = fs.readFileSync(source, 'utf8');
const version = text.match(/^# DerivedBidiClass-([\d.]+)\.txt/m)?.[1] ?? (() => { throw new Error('not a DerivedBidiClass file'); })();
// The order of BidiClass in Bidi.cs.
const names = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON', 'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI'];
const long = { Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Terminator: 'ET' };
const classes = new Uint8Array(0x110000);
const apply = (range, name) => {
  const [from, to = from] = range.split('..').map(h => parseInt(h, 16));
  const value = names.indexOf(long[name] ?? name);
  if (value < 0) throw new Error(`unknown class ${name}`);
  classes.fill(value, from, to + 1);
};
for (const m of text.matchAll(/^# @missing: ([0-9A-F.]+); (\w+)/gm)) apply(m[1], m[2]);
for (const m of text.matchAll(/^([0-9A-F.]+)\s*; (\w+)/gm)) apply(m[1], m[2]);

const starts = [], values = [];
for (let cp = 0; cp < classes.length; cp++) if (cp === 0 || classes[cp] !== classes[cp - 1]) { starts.push(cp); values.push(classes[cp]); }
const lines = (items, per) => Array.from({ length: Math.ceil(items.length / per) }, (_, i) => '        ' + items.slice(i * per, i * per + per).join(', ') + ',').join('\n');
const out = `// <auto-generated>
// Written by Bidi/generate.mjs from Unicode ${version} DerivedBidiClass.txt; do not edit.
// </auto-generated>
namespace MicroEngine.Graphics;

internal static partial class Bidi
{
    /// <summary>The Unicode version of the class table.</summary>
    public const string UnicodeVersion = "${version}";

    /// <summary>The first code point of each range of one bidirectional class, ascending (${starts.length} ranges).</summary>
    private static ReadOnlySpan<int> RangeStarts =>
    [
${lines(starts.map(s => '0x' + s.toString(16).toUpperCase()), 12)}
    ];

    /// <summary>The class of each range (a <see cref="BidiClass"/>).</summary>
    private static ReadOnlySpan<byte> RangeClasses =>
    [
${lines(values.map(String), 32)}
    ];
}
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), 'BidiClasses.g.cs');
fs.writeFileSync(target, out);
console.log(`${target}: ${starts.length} ranges, Unicode ${version}`);
